#!/usr/bin/env python
# Genera las piezas del Diseñador de formatos a partir de las fuentes de esta carpeta:
#   1) designer/Backend.g.cs     el motor de etiquetas y las acciones del puente (motor.cs + acciones.cs) convertidos en la clase Motor del programa aparte
#   2) designer/pagina.g.html    la página del Diseñador (disenador.css/.html/1-3.js)
#   3) instalador/scripts/ConfiguracionFormato.ctx   base.ctx + el botón «Diseñar formato…» que abre el programa aparte
# Las fuentes son motor.cs, acciones.cs, disenador.*; los archivos generados NO se editan a mano. Uso:  python build/disenador_formatos/generar.py
import os, re
AQUI = os.path.dirname(os.path.abspath(__file__))
RAIZ = os.path.abspath(os.path.join(AQUI, '..', '..'))


def leer(n):
    return open(os.path.join(AQUI, n), encoding='utf-8').read().replace('\r\n', '\n')


# ---------------------------------------------------------------- 1) Backend.g.cs
motor = leer('motor.cs')
lineas = []
for l in motor.split('\n'):
    if l and not l[0].isspace() and not l.startswith(('//', '{', '}', 'static ', '/*')):
        m = re.match(r'^var (\w+) = (.*)$', l)
        if m:
            nuevo = re.match(r'^new ([A-Za-z_.<>, ]+?)\s*[\(\{]', m.group(2))
            if nuevo: l = 'static ' + nuevo.group(1) + ' ' + m.group(1) + ' = ' + m.group(2)
            elif m.group(2).startswith('System.Globalization.CultureInfo'): l = 'static System.Globalization.CultureInfo ' + m.group(1) + ' = ' + m.group(2)
            else: raise SystemExit('Variable de nivel superior sin tipo conocido: ' + l)
        elif re.match(r'^[A-Za-z_][\w<>,\[\] .]*\s[A-Za-z_]\w*\s*\(', l) or re.match(r'^Dictionary<string, string> sqlRefsE', l):
            l = 'static ' + l
    lineas.append(l)
motor = '\n'.join(lineas)
acciones = leer('acciones.cs')
backend = '''// <auto-generated> Generado por build/disenador_formatos/generar.py a partir de motor.cs y acciones.cs. No se edita a mano. </auto-generated>
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Windows.Forms;

namespace BrosLMV.Disenador
{
    static partial class Motor
    {
''' + motor + '''

        public static object Despachar(string action, Dictionary<string, object> p)
        {
            object data = null; string err = null;
            {
                if (false) { }
''' + acciones.rstrip('\n') + '''
                else throw new Exception("Acción desconocida: " + action);
            }
            if (err != null) throw new Exception(err);
            return data;
        }
    }
}
'''
open(os.path.join(RAIZ, 'designer', 'Backend.g.cs'), 'w', encoding='utf-8', newline='').write(backend.replace('\n', '\r\n'))

# ---------------------------------------------------------------- 2) pagina.g.html
js = leer('disenador1.js') + '\n' + leer('disenador2.js') + '\n' + leer('disenador3.js') + '\n' + leer('disenador4.js')
pagina = '''<!doctype html><html lang="es"><head><meta charset="utf-8"><title>Diseñador de formatos</title><style>
:root{--accent:#2D6FE0;--accent-d:#1f56b8;--ink:#16263A;--muted:#64748B;--bg:#F4F6FA;--card:#FFFFFF;--line:#E5E9F0;--line-2:#EEF1F6;--ok:#16A34A;--bad:#DC2626}
*{box-sizing:border-box}html,body{height:100%}[hidden]{display:none!important}
body{margin:0;font:13px/1.5 -apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;color:var(--ink);background:var(--bg)}
.toast{position:fixed;left:50%;bottom:26px;transform:translateX(-50%) translateY(20px);background:var(--ink);color:#fff;padding:10px 16px;border-radius:10px;font-size:12.5px;opacity:0;transition:.2s;pointer-events:none;z-index:200;max-width:80vw}
.toast.show{opacity:1;transform:translateX(-50%) translateY(0)}.toast.bad{background:var(--bad)}.toast.ok{background:var(--ok)}
''' + leer('disenador.css') + '''
</style></head><body>
''' + leer('disenador.html') + '''
<div id="toast" class="toast"></div>
<script>
const INICIO = __INICIO__;
const STANDALONE = true;
const bus = {}; let _rid = 0;
function call(action, payload) { return new Promise((res, rej) => { const reqId = 'r' + (++_rid); bus[reqId] = { res, rej }; window.chrome.webview.postMessage(JSON.stringify({ reqId, action, payload: payload || {} })); }); }
window.chrome.webview.addEventListener('message', e => { const m = e.data; const h = bus[m.reqId]; if (!h) return; delete bus[m.reqId]; if (m.ok) h.res(m.data); else h.rej(new Error(m.error || 'error')); });
function toast(msg, kind) { const t = document.getElementById('toast'); t.textContent = msg; t.className = 'toast show ' + (kind || ''); clearTimeout(t._t); t._t = setTimeout(() => t.className = 'toast', 3200); }
''' + js + '''
window.addEventListener('load', () => { if (INICIO.formato) abrirDisenador(INICIO.formato); else abrirSelector(); });
</script></body></html>
'''
open(os.path.join(RAIZ, 'designer', 'pagina.g.html'), 'w', encoding='utf-8', newline='').write(pagina)

# ---------------------------------------------------------------- 3) ConfiguracionFormato.ctx: el botón abre el programa aparte
t = leer('base.ctx')
a = t.index('                else if (action == "editarHtml")')
b = t.index('                else if (action == "abrirAyudaAppPassword")')
lanzador = '''                else if (action == "editarHtml")
                {
                    // «Diseñar formato…»: abre el Diseñador como PROGRAMA APARTE (se puede minimizar y Comercial sigue libre)
                    long fidD = Convert.ToInt64(p["formatId"]);
                    string exeD = new[] { @"C:\\BrosLMV\\disenador\\BrosLMV.Disenador.exe", @"C:\\MLVTotal\\designer\\bin\\Release\\net8.0-windows\\BrosLMV.Disenador.exe", @"C:\\MLVTotal-union\\designer\\bin\\Release\\net8.0-windows\\BrosLMV.Disenador.exe" }.FirstOrDefault(File.Exists);
                    if (exeD == null) err = "No se encontró el Diseñador (BrosLMV.Disenador.exe). Reinstala BrosLMV con la versión que lo incluye.";
                    else
                    {
                        string bdD = S(ctx.Scalar("SELECT DB_NAME()"));
                        System.Diagnostics.Process.Start(new System.Diagnostics.ProcessStartInfo { FileName = exeD, Arguments = "--bd \\"" + bdD + "\\" --empresa " + owned + " --userid " + userId + " --formato " + fidD, UseShellExecute = false });
                    }
                    data = o("ok", err == null);
                }
'''
t = t[:a] + lanzador.replace('\\\\', '\\') + t[b:]
assert t.count("<button class='btn sm' onclick='editarHtml()'>Editar HTML</button>") == 1
t = t.replace("<button class='btn sm' onclick='editarHtml()'>Editar HTML</button>", "<button class='btn sm primary' onclick='editarHtml()'>Diseñar formato…</button>")
t = t.replace("async function editarHtml(){const id=+val('fmt');if(!id){toast('No hay archivo','bad');return;}await call('editarHtml',{formatId:id});}",
              "async function editarHtml(){const id=+val('fmt');if(!id){toast('No hay archivo','bad');return;}try{await call('editarHtml',{formatId:id});toast('Abriendo el Diseñador…','ok');}catch(e){toast(e.message,'bad');}}")
t = t.replace('usa “Editar HTML” para ajustarlo', 'usa “Diseñar formato…” para ajustarlo')
for _d in (('instalador', 'scripts'), ('htmlpdf',)):   # htmlpdf/ es la fuente que generar_instalador.ps1 copia a instalador/scripts
    open(os.path.join(RAIZ, *_d, 'ConfiguracionFormato.ctx'), 'w', encoding='utf-8', newline='').write(t.replace('\n', '\r\n'))
print('ok')
